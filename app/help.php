/** 화면 메뉴 키 → 도움말 항목 id (없으면 null) */
function help_anchor(string $key): ?string
{
    if ($key === '') return null;
    foreach (help_tree() as $g) {
        foreach ($g['items'] as $it) {
            if ($it['id'] === $key || in_array($key, $it['keys'], true)) return $it['id'];
        }
    }
    return null;
}
